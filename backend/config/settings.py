def env_bool(key, default=False):
    val = os.environ.get(key)
    if val is None:
        return default
    return val.strip().lower() in ('1', 'true', 'yes', 'on')


def env_list(key, default=''):
    val = os.environ.get(key, default)
    return [item.strip() for item in val.split(',') if item.strip()]


